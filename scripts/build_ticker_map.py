"""
Build sec_tickers.py: a compact ticker -> CIK lookup for the Worker.

A CIK (Central Index Key) is the SEC's permanent ID number for a company.
EDGAR's data APIs are keyed by CIK, not ticker, so we need this mapping.

SEC's full ticker file is ~10,000 rows. Downloading and parsing it on every
request would waste the Worker's CPU budget, so we bake it into a Python
module instead. Python Workers snapshot imported modules at deploy time, so
the lookup costs almost nothing per request.

Re-run occasionally (new IPOs, ticker changes):
    .venv\\Scripts\\python.exe scripts\\build_ticker_map.py
"""

from sec_local import REPO, get_json

SRC = "https://www.sec.gov/files/company_tickers.json"


def main():
    rows = get_json(SRC).values()
    mapping = {}
    for r in rows:
        t = str(r["ticker"]).upper().replace(".", "-")
        # The file lists the primary ticker first; keep the first CIK we see.
        mapping.setdefault(t, int(r["cik_str"]))

    lines = ["# GENERATED by scripts/build_ticker_map.py from SEC company_tickers.json.",
             "# Do not edit by hand. Ticker -> CIK (unpadded int).",
             "TICKER_TO_CIK = {"]
    for t in sorted(mapping):
        lines.append(f'    "{t}": {mapping[t]},')
    lines.append("}")
    lines.append("")
    out = REPO / "sec_tickers.py"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(mapping):,} tickers to {out.name} ({out.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
